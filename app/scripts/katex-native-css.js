// Writes src/lib/katexCss.generated.ts: KaTeX's stylesheet for the native
// WebView (components/MathText.tsx), with the fonts school math uses inlined as
// woff2 data URLs, so saved results typeset offline. The rarer families
// (\mathcal, \mathfrak, \mathsf, \mathtt, \mathscr) still load from the CDN.
//
//   node scripts/katex-native-css.js    # after upgrading katex
const fs = require('fs');
const path = require('path');

const dist = path.dirname(require.resolve('katex/dist/katex.min.css'));
const { version } = require('katex/package.json');
const INLINE = /^KaTeX_(Main|Math|AMS|Size[1-4])-/;
const CDN = `https://cdn.jsdelivr.net/npm/katex@${version}/dist/`;

const css = fs
  .readFileSync(path.join(dist, 'katex.min.css'), 'utf8')
  // Keep only the woff2 source of each @font-face.
  .replace(/src:url\((fonts\/[^)]+\.woff2)\) format\("woff2"\)[^}]*/g, (_, file) => {
    const name = path.basename(file);
    const url = INLINE.test(name)
      ? 'data:font/woff2;base64,' + fs.readFileSync(path.join(dist, file)).toString('base64')
      : CDN + file;
    return `src:url(${url}) format("woff2")`;
  });
if (/url\(fonts\//.test(css)) throw new Error('katex-native-css: a font URL was not rewritten');

const out = path.join(__dirname, '..', 'src', 'lib', 'katexCss.generated.ts');
fs.writeFileSync(
  out,
  `// Generated by scripts/katex-native-css.js from katex ${version}. Do not edit.\n` +
    `export const KATEX_CSS_VERSION = ${JSON.stringify(version)};\n` +
    `export const KATEX_CSS = ${JSON.stringify(css)};\n`,
);
console.log(`katex-native-css: wrote ${path.relative(process.cwd(), out)} (${Math.round(css.length / 1024)} KB)`);
